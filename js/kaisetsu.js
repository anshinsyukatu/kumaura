/** もっとも色濃い通変星（出現数が最大。同数なら年柱→月柱→時柱の順に優先） */
function strongestTsuhen(r) {
  var best = r.tsuhen[0];
  var order = [0, 1, 3];
  for (var k = 0; k < order.length; k++) {
    var t = r.tsuhen[order[k]];
    if (r.tsuhenCount[t] > r.tsuhenCount[best]) best = t;
  }
  return best;
}

/** 2番目に色濃い通変星。年・月・時柱すべてが最強と同じ星なら -1。 */
function secondStrongestTsuhen(r, strongest) {
  var best = -1;
  var order = [0, 1, 3];
  for (var k = 0; k < order.length; k++) {
    var t = r.tsuhen[order[k]];
    if (t === strongest) continue;
    if (best < 0 || r.tsuhenCount[t] > r.tsuhenCount[best]) best = t;
  }
  return best;
}

