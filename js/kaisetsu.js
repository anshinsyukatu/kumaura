    + _levelLabel(best.level) + "）です。"
    + "逆にペース配分が大事な時期は約"
    + _intDiv(worst.startMonths, 12) + "歳〜" + _intDiv(worst.startMonths + 120, 12) + "歳ごろ（"
    + _kanjiOf(worst.pillarIdx) + "の大運、傾向："
    + _levelLabel(worst.level) + "）とされます。"
