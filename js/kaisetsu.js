/** ageMonths（生まれてからの経過月数）の時点で進行中の大運。まだ始まっていなければ null。 */
function currentDaiun(r, ageMonths) {
  var cur = null;
  for (var k = 0; k < r.daiun.length; k++) {
    var du = r.daiun[k];
    if (du.startMonths <= ageMonths) cur = du;
  }
  return cur;
}

/** 基準年から5年分（基準年〜基準年+4）の年運を r.nenun から取り出す。 */
function fiveYears(r, refYear) {
  var out = new Array(5);
  for (var i = 0; i < 5; i++) out[i] = null;
  for (var k = 0; k < r.nenun.length; k++) {
    var n = r.nenun[k];
    var d = n.year - refYear;
    if (d >= 0 && d < 5) out[d] = n;
  }
  return out;
}

/** 5年分の年運の流れパターン。0=後半上向き / 1=前半山場 / 2=注意多め波あり / 3=追い風多め / 4=穏やか */
function outlookPattern(five) {
  var firstAvg = (five[0].level + five[1].level) / 2.0;
  var secondAvg = (five[3].level + five[4].level) / 2.0;
  var good = 0, warn = 0;
  for (var k = 0; k < five.length; k++) {
    var n = five[k];
    if (n.level >= 6.0) good++;
    else if (n.level < 4.5) warn++;
  }
  if (secondAvg - firstAvg >= 1.0) return 0;
  if (firstAvg - secondAvg >= 1.0) return 1;
  if (warn >= 3) return 2;
  if (good >= 3) return 3;
  return 4;
}

/** 見通しの「今後予想されること」：これから5年の流れのまとめ。引数 r / cur は呼び出し側の互換のために残す（本文では使わない）。 */
function outlookForecast(r, cur, five) {
  var sb = "";
  sb += "これから5年：";
  for (var i = 0; i < five.length; i++) {
    if (i > 0) sb += " → ";
    sb += five[i].year + "年 " + _levelLabel(five[i].level);
  }
  sb += "\n";
  var pattern = outlookPattern(five);
  var best = five[0], worst = five[0];
  for (var k2 = 0; k2 < five.length; k2++) {
    var n2 = five[k2];
    if (n2.level > best.level) best = n2;
    if (n2.level < worst.level) worst = n2;
  }
  switch (pattern) {
    case 0:
      sb += "前半は助走で、後半にかけて上向いていく流れです。";
      break;
    case 1:
      sb += "前半が山場で、後半は落ち着いていく流れです。";
      break;
    case 2: {
      var warn = 0;
      for (var k3 = 0; k3 < five.length; k3++) if (five[k3].level < 4.5) warn++;
      sb += "「注意」の年が" + warn + "年あって、波のある流れです。";
      break;
    }
    case 3:
      sb += "追い風の年が多めで、全体に明るい流れです。";
      break;
    default:
      sb += "大きな波はなく、穏やかな流れです。";
  }
  if (pattern === 2) {
    sb += "年ごとのメリハリが大事になりそうです。";
  } else if (worst.level < 4.5) {
    sb += "いちばん追い風は" + best.year + "年（"
      + _levelLabel(best.level) + "）で、"
      + worst.year + "年は「注意」の年なのでペースを落としたいところです。";
  } else {
    sb += "いちばん追い風は" + best.year + "年（"
      + _levelLabel(best.level) + "）です。";
  }
  return sb;
}

/** アドバイス：今の大運の傾向に応じた心がけ＋5年の流れに応じた過ごし方のヒント＋パターン別の追加ヒント＋締め。 */
function outlookAdvice(r, cur, five) {
  var sb = "";
  if (cur === null || cur === undefined) {
    sb += "最初の大運が始まるまでの今は、焦らず好きなこと・得意なことを増やしていく時期です。"
      + "いろいろ試してみる中で、自分の「これ」が見つかりやすくなります。";
  } else {
    var label = _levelLabel(cur.level);
    if (label === "好調") {
      sb += "大運が追い風の今は、やりたいことに少し欲張りになってもいい時期です。"
        + "迷っていたことがあるなら、この流れの中で一歩踏み出してみるのもよさそうです。";
    } else if (label === "平穏") {
      sb += "大運は平穏な流れなので、派手な勝負より土台づくりが向いている時期です。"
        + "生活リズムや身の回りを整えておくと、次の追い風が来たときに動きやすくなります。";
    } else {
      sb += "大運はペース配分が大事な時期です。新しいことを広げすぎず、今あるものを守って磨く意識が合っています。"
        + "しんどいときは一人で抱え込まず、周りの手を借りてみてください。";
    }
  }
  switch (outlookPattern(five)) {
    case 0:
      sb += "年ごとの流れは後半に向けて上向くので、今は種まきのつもりで準備を進めるのがおすすめです。"
        + "後半の追い風に乗れるよう、計画を温めておきましょう。";
      break;
    case 1:
      sb += "年ごとの流れは前半が山場なので、勝負どころは早めに済ませて、"
        + "後半は仕上げと振り返りに使う配分が合いそうです。";
      break;
    case 2:
      sb += "年によって波があるので、調子のいい年に進めて、「注意」の年は無理をしない、というメリハリを意識してみてください。"
        + "大事な予定は、できれば追い風の年に寄せるのがおすすめです。";
      break;
    case 3:
      sb += "年ごとの流れも明るめなので、気になっていたことにまとめて挑戦してみるのもいい時期です。"
        + "調子がいいときほど、休むことも予定に入れておくのが長続きのコツです。";
      break;
    default:
      sb += "年ごとの流れが穏やかな今は、コツコツ続けることが一番の近道になりそうです。"
        + "小さな習慣を一つ決めて続けてみると、後からじわじわ効いてきます。";
  }
  sb += ADVICE_EXTRA[outlookPattern(five)];
  sb += "どれも目安です。ピンとくる部分だけ、日常の中で試してみてください。";
  return sb;
}

